#!/usr/bin/env python3
"""Builds AzerothPlus's tooltip data (`addons/AzerothPlus/infodb.lua`) from the same dump as
scripts/questdb.py:

    ssh root@server bash -s < scripts/questdb-dump.sh > world.tsv   # read-only SELECTs
    scripts/infodb.py world.tsv > addons/AzerothPlus/infodb.lua

1.12 tells the interface neither what a vendor pays for an item nor a creature's health (only a
percentage), so both come from the world database: each item's sell price in copper by id, and
each creature's health at its lowest and highest level by name.
"""

import sys

from questdb import lua_string, read_tables


def main():
    tables = read_tables(sys.argv[1])
    out = sys.stdout
    out.write("-- Generated by scripts/infodb.py from a CMaNGOS Classic world database; do not edit.\n")
    out.write("-- prices: item id = copper a vendor pays for one.\n")
    out.write("-- health: creature name = {min level, max level, health at min, health at max}.\n")
    out.write("AzerothPlusInfoDB = {\nprices = {\n")
    prices = sorted((int(e), int(p)) for e, p in tables["sell"])
    for entry, price in prices:
        out.write(f"[{entry}]={price},\n")
    out.write("},\nhealth = {\n")
    health = sorted(tables["health"])
    for name, lo, hi, hlo, hhi in health:
        if name:
            out.write(f"[{lua_string(name)}]={{{lo},{hi},{hlo},{hhi}}},\n")
    out.write("},\n}\n")
    print(f"infodb: {len(prices)} prices, {len(health)} creatures", file=sys.stderr)


if __name__ == "__main__":
    main()
